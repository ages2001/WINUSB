#!/usr/bin/env python3
# mkgpio.py - builds src/core/gpiotab.h (Intel GPIO controllers: communities, pad groups and
# the ACPI GPIO numbering) from the pinctrl tables of Linux (drivers/pinctrl/intel).
# usage: mkgpio.py <linux>/drivers/pinctrl/intel > src/core/gpiotab.h
import os, re, sys

src = sys.argv[1]
files = ["sunrisepoint", "broxton", "geminilake", "cannonlake", "icelake", "jasperlake",
         "elkhartlake", "tigerlake", "alderlake", "meteorlake", "meteorpoint"]

def ival(t, base_s):
    t = t.strip()
    if t == "INTEL_GPIO_BASE_NOMAP": return -1
    if t == "INTEL_GPIO_BASE_ZERO": return 0
    if t == "INTEL_GPIO_BASE_MATCH": return base_s
    return int(t, 0)

groups = []        # (base, size, gbase)
comms = []         # (pin_base, npins, barno, comid, g0, ng)
socs = []          # (hid, uid, c0, nc, family)

for f in files:
    text = open(os.path.join(src, "pinctrl-%s.c" % f)).read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    macros = {}
    for m in re.finditer(r"#define\s+(\w+_COMMUNITY)\(([^)]*)\)\s*\\\s*\n\s*INTEL_COMMUNITY_(GPPS|SIZE)\(([^)]*)\)", text):
        macros[m.group(1)] = (m.group(2).replace(" ", "").split(","), m.group(3),
                              m.group(4).replace(" ", "").split(","))
    gpps = {}
    for m in re.finditer(r"static const struct intel_padgroup (\w+)\[\] = \{(.*?)\};", text, re.S):
        lst = []
        for g in re.finditer(r"INTEL_GPP\(([^)]*)\)", m.group(2)):
            r, s, e, gb = [x.strip() for x in g.group(1).split(",")]
            s, e = int(s, 0), int(e, 0)
            lst.append((s, e - s + 1, ival(gb, s)))
        gpps[m.group(1)] = lst
    commarr = {}
    for m in re.finditer(r"static const struct intel_community (\w+)\[\] = \{(.*?)\};", text, re.S):
        lst = []
        for c in re.finditer(r"(\w+_COMMUNITY)\(([^)]*)\)", m.group(2)):
            params, kind, body = macros[c.group(1)]
            args = dict(zip(params, [x.strip() for x in c.group(2).split(",")]))
            b, s, e = [int(args.get(body[i], body[i]), 0) for i in range(3)]
            if kind == "GPPS":
                gname = args[body[3]]
                gl = gpps[gname]
                mm = re.search(r"community(\d+)", gname)
                comid = int(mm.group(1)) if mm else b
            else:
                gs = int(args.get(body[3], body[3]), 0)
                gl, n, base = [], e - s + 1, s
                while n > 0:
                    gl.append((base, min(gs, n), base))
                    base += gs
                    n -= gs
                comid = [0, 1, 3][b] if f == "sunrisepoint" else b
            lst.append((s, e - s + 1, b, comid, gl))
        commarr[m.group(1)] = lst
    socd = {}
    for m in re.finditer(r"static const struct intel_pinctrl_soc_data (\w+) = \{(.*?)\};", text, re.S):
        uid = re.search(r"\.uid\s*=\s*\"(\d+)\"", m.group(2))
        cm = re.search(r"\.communities\s*=\s*(\w+)", m.group(2))
        socd[m.group(1)] = (int(uid.group(1)) if uid else 0, commarr[cm.group(1)])
    socarr = {}
    for m in re.finditer(r"static const struct intel_pinctrl_soc_data \*(\w+)\[\] = \{(.*?)\};", text, re.S):
        socarr[m.group(1)] = re.findall(r"&(\w+)", m.group(2))
    mt = re.search(r"static const struct acpi_device_id \w+\[\] = \{(.*?)\};", text, re.S)
    for hid, ref in re.findall(r"\{\s*\"(\w+)\",\s*\(kernel_ulong_t\)&?(\w+)\s*\}", mt.group(1)):
        for sname in (socarr[ref] if ref in socarr else [ref]):
            uid, cl = socd[sname]
            c0 = len(comms)
            for (s, n, b, comid, gl) in cl:
                g0 = len(groups)
                groups.extend(gl)
                comms.append((s, n, b, comid, g0, len(gl)))
            socs.append((hid, uid, c0, len(cl), f))

fam = {"sunrisepoint": "GF_SPT", "broxton": "GF_BXT", "geminilake": "GF_GLK"}
print("/* gpiotab.h - Intel GPIO controllers (generated by tools/mkgpio.py from the pinctrl tables of")
print("   Linux): ACPI id, communities, pad groups and the ACPI GPIO number of each group */")
print("static const struct gpgrp gpgrps[] = {")
for i in range(0, len(groups), 4):
    print("    " + " ".join("{ %d, %d, %d }," % g for g in groups[i:i + 4]))
print("};")
print("static const struct gpcom gpcoms[] = {")
for i in range(0, len(comms), 3):
    print("    " + " ".join("{ %d, %d, %d, %d, %d, %d }," % c for c in comms[i:i + 3]))
print("};")
print("static const struct gpsoc gpsocs[] = {")
for (hid, uid, c0, nc, f) in socs:
    print("    { \"%s\", %d, %d, %d, %s }," % (hid, uid, c0, nc, fam.get(f, "GF_CNL" if f not in ("meteorlake", "meteorpoint") else "GF_MTL")))
print("    { NULL, 0, 0, 0, 0 }")
print("};")
