#!/usr/bin/env python3
"""gensrc.py: polyphase windowed-sinc tables for the W3 sound engine (core/srctab.h).
16 taps, 64 phases; one table per cutoff (up-sampling, and down-sampling ratios 1.5, 2, 4)."""
import math, sys
TAPS, PH = 16, 64
cuts = [("up", 0.46), ("d15", 0.46 / 1.5), ("d2", 0.46 / 2.0), ("d4", 0.46 / 4.0)]
out = ["/* srctab.h - generated by tools/gensrc.py: polyphase windowed-sinc filters */",
       "#define SRC_TAPS %d" % TAPS, "#define SRC_PHASES %d" % PH, "#define SRC_TABLES %d" % len(cuts),
       "static const s16 src_tab[SRC_TABLES][SRC_PHASES][SRC_TAPS] = {"]
for name, fc in cuts:
    out.append("    { /* %s, cutoff %.3f */" % (name, fc))
    for p in range(PH):
        f = p / PH
        w = []
        for k in range(TAPS):
            t = k - (TAPS // 2 - 1) - f          # distance from the output point
            x = 2 * fc * t
            s = 1.0 if abs(x) < 1e-9 else math.sin(math.pi * x) / (math.pi * x)
            n = (k - f + 0.5) / TAPS              # Blackman window over the taps
            win = 0.42 - 0.5 * math.cos(2 * math.pi * n) + 0.08 * math.cos(4 * math.pi * n)
            w.append(2 * fc * s * max(win, 0.0))
        tot = sum(w)
        q = [int(round(v / tot * 32767)) for v in w]
        q[TAPS // 2 - 1] += 32767 - sum(q)        # exact unity gain
        out.append("        { " + ", ".join(str(v) for v in q) + " },")
    out.append("    },")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
