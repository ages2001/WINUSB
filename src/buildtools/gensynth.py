#!/usr/bin/env python3
"""gensynth.py: tables of the W3 FM synthesizer (core/synthtab.h).
sine wave, 2^(i/768) for pitch, MIDI note frequencies, envelope decay factors."""
import math, sys
out = ["/* synthtab.h - generated by tools/gensynth.py */",
       "#define SIN_BITS 10",
       "#define ENV_RATE 750                  /* envelope steps per second */"]
out.append("static const s16 sintab[1024] = {")
v = [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1024)]
for i in range(0, 1024, 16):
    out.append("    " + ", ".join(str(x) for x in v[i:i + 16]) + ",")
out.append("};")
out.append("/* 2^(i/768) in 1.16 fixed point (1/64 semitone steps over one octave) */")
out.append("static const u32 expotab[768] = {")
v = [int(round(65536 * 2 ** (i / 768))) for i in range(768)]
for i in range(0, 768, 12):
    out.append("    " + ", ".join(str(x) for x in v[i:i + 12]) + ",")
out.append("};")
out.append("/* MIDI note frequencies, Hz * 256 */")
out.append("static const u32 notehz[128] = {")
v = [int(round(256 * 440 * 2 ** ((n - 69) / 12))) for n in range(128)]
for i in range(0, 128, 12):
    out.append("    " + ", ".join(str(x) for x in v[i:i + 12]) + ",")
out.append("};")
out.append("/* envelope time index t (time 2^(t/6) ms to fall by 60 dB): factor per step, 0.16 */")
out.append("static const u16 decf[96] = {")
v = []
for t in range(96):
    steps = max(2 ** (t / 6) * 750 / 1000, 1.0)
    v.append(min(65535, int(round(65536 * 10 ** (-3 / steps)))))
for i in range(0, 96, 12):
    out.append("    " + ", ".join(str(x) for x in v[i:i + 12]) + ",")
out.append("};")
out.append("/* time index -> envelope steps */")
out.append("static const u32 tsteps[96] = {")
v = [max(1, int(round(2 ** (t / 6) * 750 / 1000))) for t in range(96)]
for i in range(0, 96, 12):
    out.append("    " + ", ".join(str(x) for x in v[i:i + 12]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
